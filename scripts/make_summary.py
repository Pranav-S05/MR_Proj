def read_csv(name):
    p = RES / f"{name}.csv"
    if not p.exists():
        return None
    rows = defaultdict(dict)
    for r in csv.DictReader(open(p)):
        rows[r["method"]][r["seq"]] = (float(r["ate_chain"]), float(r["ate_loops"]), r.get("auto_pick", ""))
    return rows


def paired(rows, method, idx=1):
    seqs = sorted(s for s in rows["none"] if s in rows.get(method, {}))
    base = np.array([rows["none"][s][idx] for s in seqs])
    v = np.array([rows[method][s][idx] for s in seqs])
    lr = np.log(v / base)
    better = int((lr < np.log(0.995)).sum())
    worse = int((lr > np.log(1.005)).sum())
    p = stats.wilcoxon(lr).pvalue if np.any(lr != 0) else 1.0
    rng = np.random.default_rng(0)
    boot = rng.integers(0, len(seqs), (10000, len(seqs)))
    ch = v[boot].mean(1) / base[boot].mean(1) - 1
    worst = int(np.argmax(lr))
    return dict(seqs=seqs, base=base, v=v, n=len(seqs), mean0=base.mean(), mean1=v.mean(),
                change=v.mean() / base.mean() - 1, gmean=float(np.exp(lr.mean())), better=better, worse=worse,
                p=float(p), worst_ratio=float(np.exp(lr.max())), worst_seq=seqs[worst],
                ci=np.percentile(ch, [2.5, 97.5]), ratios=dict(zip(seqs, np.exp(lr))))


def label(st):
    if st is None:
        return "not run"
    if st["change"] <= -0.15 and st["gmean"] <= 0.90 and st["p"] < 0.05 and st["worst_ratio"] <= 1.25:
        return "clear improvement"
    if st["change"] <= -0.10 and st["gmean"] < 1 and st["better"] >= 7:
        return "improvement"
    return "no reliable gain"


def stat_line(st):
    return (f"mean {st['mean0']:.2f} -> {st['mean1']:.2f} m ({100 * st['change']:+.1f}%), geometric-mean ratio "
            f"{st['gmean']:.3f}, {st['better']} better / {st['worse']} worse of {st['n']}, Wilcoxon p {st['p']:.3f}, "
            f"worst {st['worst_seq']} x{st['worst_ratio']:.2f}, 95% interval of the mean change "
            f"[{100 * st['ci'][0]:+.0f}%, {100 * st['ci'][1]:+.0f}%]")


